# Checks SEC EDGAR for each company's IPO registration filings and writes edgar-filings.js:
#   DRS / DRS/A  confidential draft registration statement (visible only once released with the public filing)
#   S-1          public registration statement          S-1/A  prospectus amendments        424B4  final prospectus (priced)
# Usage:  powershell -File .claude\work\edgar-check.ps1 [-Only id1,id2]
# Company ids/names come from quant-data.js. Override a wrong or missing match in .claude\work\edgar-cik.csv (id,cik).
# Names that match no EDGAR filer are simply reported as "no filings"; review the printed "Unmatched" list for misses.
param([string[]]$Only, [string]$Contact = 'itu@perennial.net.au', [switch]$Refilter)
# edgar-exclude.csv lists ids whose EDGAR match is a different company with the same name, or is stale; they are dropped from the output.
# -Refilter re-applies that list to the existing edgar-filings.js without calling EDGAR again.
$ErrorActionPreference = 'Stop'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
$root = Split-Path (Split-Path $PSScriptRoot)
$H = @{ 'User-Agent' = "Perennial Partners $Contact" }   # SEC requires a contact in the User-Agent
$utf8 = New-Object Text.UTF8Encoding($false)

$js = [IO.File]::ReadAllText((Join-Path $root 'quant-data.js'), [Text.Encoding]::UTF8)
$pbu = Join-Path $root 'pitchbook-universe.js'   # companies added from the PitchBook export are checked too
if (Test-Path $pbu) { $js += "`n" + [IO.File]::ReadAllText($pbu, [Text.Encoding]::UTF8) }
$cos = foreach ($m in [regex]::Matches($js, '(?m)^\{"id":"([^"]+)","name":"((?:[^"\\]|\\.)*)"')) {
  [pscustomobject]@{ id = $m.Groups[1].Value; name = [regex]::Unescape($m.Groups[2].Value) } }
if ($Only) { $Only = $Only -split ','; $cos = $cos | Where-Object { $Only -contains $_.id } }   # -File passes "a,b" as one string

$ovr = @{}; $ovrFile = Join-Path $PSScriptRoot 'edgar-cik.csv'
if (Test-Path $ovrFile) { foreach ($r in Import-Csv $ovrFile) { $ovr[$r.id] = $r.cik } }

function Norm($s) {
  $s = ($s -replace '\(.*?\)', '').ToLower() -replace '&', ' and ' -replace '[^a-z0-9 ]', ' '
  $s = $s -replace '\b(inc|incorporated|corp|corporation|ltd|limited|llc|plc|co|company|holdings|holding|the)\b', ' '
  ($s -replace '\s+', ' ').Trim() }
function Get-Json($url) { Start-Sleep -Milliseconds 150; Invoke-RestMethod -Uri $url -Headers $H -TimeoutSec 40 }

$excl = @{}; $exclFile = Join-Path $PSScriptRoot 'edgar-exclude.csv'
if (Test-Path $exclFile) { foreach ($r in Import-Csv $exclFile) { $excl[$r.id] = $r.reason } }
$edgarJs = Join-Path $root 'edgar-filings.js'
$hdr = "// Generated by .claude/work/edgar-check.ps1 from SEC EDGAR - do not edit; re-run the script.`n" +
  "// Filings per company id: DRS (confidential draft, shown once released), S-1, S-1/A (amendments), 424B4 (final prospectus). n = count, first/last = filing dates.`n"
if ($Refilter) {
  $t = [IO.File]::ReadAllText($edgarJs, [Text.Encoding]::UTF8)
  $asofOld = [regex]::Match($t, 'EDGAR_ASOF = "([^"]+)"').Groups[1].Value
  $obj = ([regex]::Match($t, '(?s)window\.EDGAR = (\{.*\});').Groups[1].Value) | ConvertFrom-Json
  $keep = [ordered]@{}; $dropped = @()
  foreach ($p in $obj.PSObject.Properties) { if ($excl.ContainsKey($p.Name)) { $dropped += $p.Name } else { $keep[$p.Name] = $p.Value } }
  [IO.File]::WriteAllText($edgarJs, ($hdr + "window.EDGAR_ASOF = `"$asofOld`";`nwindow.EDGAR = " + (ConvertTo-Json $keep -Depth 6) + ";`n"), $utf8)
  Write-Host "Kept $($keep.Count): $($keep.Keys -join ', ')"; Write-Host "Dropped $($dropped.Count): $($dropped -join ', ')"; return
}

$out = [ordered]@{}; $unmatched = @(); $i = 0
foreach ($c in $cos) {
  $i++; if ($i % 25 -eq 0) { Write-Host "  $i / $($cos.Count)" }
  if ($excl.ContainsKey($c.id)) { continue }
  try {
    # Find the filer: EDGAR's entity search (the same lookup as the EDGAR company box), exact name match after normalising legal suffixes.
    # Full-text search is not used for this: it misses filers whose own documents are not indexed under the company name.
    $ciks = @(); $qn = ($c.name -split ' / ')[0] -replace '\s*\(.*?\)', ''
    if ($ovr[$c.id]) { $ciks = @($ovr[$c.id]) } else {
      $r = Get-Json ('https://efts.sec.gov/LATEST/search-index?keysTyped=' + [uri]::EscapeDataString($qn))
      $want = Norm $qn
      $ciks = @($r.hits.hits | Where-Object { (Norm $_._source.entity) -eq $want } | Select-Object -First 4 | ForEach-Object { $_._id }) }
    $sub = $null; $rows = $null
    foreach ($cik0 in $ciks) {
      $cik = ('{0:D10}' -f [int64]$cik0)
      $s1 = Get-Json "https://data.sec.gov/submissions/CIK$cik.json"; $f = $s1.filings.recent
      $rr = @(for ($k = 0; $k -lt $f.form.Count; $k++) { if ($f.form[$k] -in 'DRS', 'DRS/A', 'S-1', 'S-1/A', '424B4') { [pscustomobject]@{ form = $f.form[$k]; date = $f.filingDate[$k] } } })
      if ($rr.Count) { $sub = $s1; $rows = $rr; break } }
    if (-not $rows) { continue }
    $e = [ordered]@{ cik = $cik; entity = $sub.name }
    foreach ($form in 'DRS', 'DRS/A', 'S-1', 'S-1/A', '424B4') {
      $g = @($rows | Where-Object form -eq $form | Sort-Object date)
      if ($g.Count) { $e[$form] = [ordered]@{ n = $g.Count; first = $g[0].date; last = $g[-1].date } }
    }
    $out[$c.id] = $e
  } catch { Write-Warning "$($c.name): $($_.Exception.Message)"; $unmatched += $c.name }
}

$body = "// Generated by .claude/work/edgar-check.ps1 from SEC EDGAR - do not edit; re-run the script.`n" +
  "// Filings per company id: DRS (confidential draft, shown once released), S-1, S-1/A (amendments), 424B4 (final prospectus). n = count, first/last = filing dates.`n" +
  "window.EDGAR_ASOF = `"$(Get-Date -Format yyyy-MM-dd)`";`nwindow.EDGAR = " + (ConvertTo-Json $out -Depth 6) + ";`n"
if ($Only) { Write-Host ($out | ConvertTo-Json -Depth 6); return }
[IO.File]::WriteAllText((Join-Path $root 'edgar-filings.js'), $body, $utf8)
Write-Host "Companies checked: $($cos.Count) · with registration filings: $($out.Count)"
$out.Keys | ForEach-Object { $e = $out[$_]; "{0,-18} {1}  S-1 {2}  S-1/A {3}  DRS {4}" -f $_, $e.entity, $(if ($e['S-1']) { $e['S-1'].first } else { '-' }), $(if ($e['S-1/A']) { "$($e['S-1/A'].n) (last $($e['S-1/A'].last))" } else { '-' }), $(if ($e['DRS']) { $e['DRS'].first } else { '-' }) }
if ($unmatched) { "Errors: " + ($unmatched -join ', ') }
