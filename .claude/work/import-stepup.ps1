# Reads the Inputs sheet of step_up_analysis.xlsx and writes stepup-inputs.js, which the dashboard's "Step-up at each stage" section calculates from.
# The workbook stays the place to change an input: edit the Inputs sheet (PitchBook value, date, override value, override date), then re-run this script.
# (The multiples, months and medians are not read from the Summary sheet; the dashboard recalculates them from these inputs with the same formulas.)
# Usage:  powershell -File .claude\work\import-stepup.ps1 -Xlsx "C:\path\step_up_analysis.xlsx"
param([Parameter(Mandatory)][string]$Xlsx)
$ErrorActionPreference = 'Stop'
$root = Split-Path (Split-Path $PSScriptRoot)
$utf8 = New-Object Text.UTF8Encoding($false)
Add-Type -AssemblyName System.IO.Compression.FileSystem
$tmp = Join-Path $env:TEMP ('stepx_' + [guid]::NewGuid().ToString('N')); [IO.Compression.ZipFile]::ExtractToDirectory($Xlsx, $tmp)
try {
  $ss = New-Object Collections.Generic.List[string]
  if (Test-Path "$tmp\xl\sharedStrings.xml") { $x = New-Object Xml.XmlDocument; $x.Load("$tmp\xl\sharedStrings.xml"); foreach ($si in $x.sst.si) { $ss.Add((($si.SelectNodes('.//*[local-name()="t"]') | ForEach-Object { $_.InnerText }) -join '')) } }
  # Find the Inputs sheet file through the workbook relationships.
  $wb = New-Object Xml.XmlDocument; $wb.Load("$tmp\xl\workbook.xml"); $rels = New-Object Xml.XmlDocument; $rels.Load("$tmp\xl\_rels\workbook.xml.rels")
  $sh = $wb.SelectNodes('//*[local-name()="sheet"]') | Where-Object { $_.GetAttribute('name') -eq 'Inputs' } | Select-Object -First 1
  if (-not $sh) { throw 'No sheet named Inputs in the workbook' }
  $rid = $sh.GetAttribute('id', 'http://schemas.openxmlformats.org/officeDocument/2006/relationships')
  $target = ($rels.SelectNodes('//*[local-name()="Relationship"]') | Where-Object { $_.GetAttribute('Id') -eq $rid }).GetAttribute('Target')
  $path = Join-Path "$tmp\xl" ($target -replace '^/xl/', '' -replace '/', '\')
  $s = New-Object Xml.XmlDocument; $s.Load($path); $ns = New-Object Xml.XmlNamespaceManager($s.NameTable); $ns.AddNamespace('m', 'http://schemas.openxmlformats.org/spreadsheetml/2006/main')
  $grid = @{}
  foreach ($row in $s.SelectNodes('//m:sheetData/m:row', $ns)) {
    $h = @{}
    foreach ($c in $row.SelectNodes('m:c', $ns)) {
      $v = $c.SelectSingleNode('m:v', $ns); $val = $null
      if ($v) { $val = if ($c.t -eq 's') { $ss[[int]$v.InnerText] } else { $v.InnerText } } elseif ($c.SelectSingleNode('m:is', $ns)) { $val = $c.SelectSingleNode('m:is', $ns).InnerText }
      $h[($c.r -replace '\d', '')] = $val }
    $grid[[int]$row.r] = $h }
} finally { Remove-Item $tmp -Recurse -Force }

function Num($v) { $d = 0.0; if ([double]::TryParse([string]$v, [Globalization.NumberStyles]::Float, [Globalization.CultureInfo]::InvariantCulture, [ref]$d)) { $d } else { $null } }
function Dt($v) { $n = Num $v; if ($n -eq $null) { $null } else { ([datetime]'1899-12-30').AddDays($n).ToString('yyyy-MM-dd') } }
$markOf = @{ 'Late Growth entry' = 'entry'; 'Pre-IPO mark' = 'pre'; 'Exit' = 'exit' }
$rows = New-Object Collections.Generic.List[object]
foreach ($r in ($grid.Keys | Sort-Object)) {
  $h = $grid[$r]; if (-not $h['A'] -or -not $markOf.ContainsKey([string]$h['B'])) { continue }
  $rows.Add([ordered]@{ co = $h['A']; mark = $markOf[[string]$h['B']]; dealType = $h['C']; pbNo = $(if ($h['D']) { [int](Num $h['D']) } else { $null }); dealId = $h['E']
    pbDate = Dt $h['F']; pbAnnounced = Dt $h['G']; dateOverride = Dt $h['H']; pbVal = Num $h['J']; status = $h['K']; valOverride = Num $h['L']; note = $h['N']; src = $h['O'] }) }
if (-not $rows.Count) { throw 'No input rows found on the Inputs sheet (expected Company, Mark, ... in columns A-O from row 5)' }
$cos = @($rows | ForEach-Object { $_.co } | Select-Object -Unique)
$body = "// Generated by .claude/work/import-stepup.ps1 from step_up_analysis.xlsx (Inputs sheet). Change a value in the workbook and re-run the script, or edit this file.`n" +
  "// One row per company and mark. Valuations are post-money, US`$ millions. A value or date override replaces the PitchBook figure; the note explains it.`n" +
  "// The dashboard calculates the multiples, months (ROUND(days / 30.4375)) and medians from these rows.`n" +
  "window.STEPUP = " + ([ordered]@{ source = 'PitchBook deal records'; asof = (Get-Date -Format 'yyyy-MM-dd'); capX = 4.5; rows = $rows } | ConvertTo-Json -Depth 5) + ";`n"
[IO.File]::WriteAllText((Join-Path $root 'stepup-inputs.js'), $body, $utf8)
Write-Host "Wrote stepup-inputs.js: $($rows.Count) rows, $($cos.Count) companies ($($cos -join ', '))"
